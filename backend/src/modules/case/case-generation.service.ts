import { caseRepository } from './case.repository';
import { diseaseRepository } from '../disease/disease.repository';
import { earlyWarningService } from '../early-warning/early-warning.service';
import { ageFromBirthDate, ageGroupFromAge } from '../../helper/age';
import { prisma } from '../../configuration/prisma';

/** Fire-and-forget early warning recheck. */
function scheduleEarlyWarning(barangayId: string, diseaseId: string): void {
  setImmediate(() => {
    void earlyWarningService.runCheck(barangayId, diseaseId);
  });
}

interface PatientContext {
  id: string;
  birthDate: Date;
  sex: string | null;
  barangayId: string | null;
}

interface DiagnosisInput {
  diseaseId?: string;
  certainty: 'SUSPECTED' | 'PROBABLE' | 'CONFIRMED';
}

/** Find an ongoing surveillance case for the same patient and disease. */
export async function findOngoingCase(patientId: string, diseaseId: string) {
  return prisma.case.findFirst({
    where: {
      patientId,
      diseaseId,
      outcome: 'ONGOING',
    },
  });
}

/**
 * Create a SUSPECTED case when a notifiable disease is selected at patient registration.
 * Skips if an ongoing case already exists for the same patient + disease.
 */
export async function createSuspectedFromRegistration(
  patient: PatientContext,
  diseaseId: string,
  reportedBy: string
): Promise<void> {
  if (!patient.barangayId) return;

  const disease = await diseaseRepository.findById(diseaseId);
  if (!disease || !disease.isNotifiable || !disease.isActive) return;

  const existing = await findOngoingCase(patient.id, diseaseId);
  if (existing) return;

  const age = ageFromBirthDate(patient.birthDate);
  const ageGroup = ageGroupFromAge(age);

  await caseRepository.create({
    disease: { connect: { id: diseaseId } },
    barangay: { connect: { id: patient.barangayId } },
    reporter: { connect: { id: reportedBy } },
    patient: { connect: { id: patient.id } },
    autoGenerated: true,
    dateReported: new Date(),
    age,
    ageGroup,
    sex: patient.sex ?? undefined,
    status: 'SUSPECTED',
    outcome: 'ONGOING',
    source: 'RHU',
    notes: 'Auto-generated from patient registration.',
  });

  scheduleEarlyWarning(patient.barangayId, diseaseId);
}

/**
 * Upsert a CONFIRMED case from a notifiable, confirmed encounter diagnosis.
 * Upgrades an existing SUSPECTED case; otherwise creates a new CONFIRMED case.
 */
export async function upsertConfirmedFromEncounter(params: {
  patient: PatientContext;
  diagnosis: DiagnosisInput;
  encounterId: string;
  encounterDate: Date;
  facilityId: string | null;
  reportedBy: string;
  skipIfEncounterCaseExists?: boolean;
}): Promise<void> {
  const { patient, diagnosis, encounterId, encounterDate, facilityId, reportedBy, skipIfEncounterCaseExists } =
    params;

  if (!patient.barangayId) return;
  if (!diagnosis.diseaseId || diagnosis.certainty !== 'CONFIRMED') return;

  const disease = await diseaseRepository.findById(diagnosis.diseaseId);
  if (!disease || !disease.isNotifiable || !disease.isActive) return;

  if (skipIfEncounterCaseExists) {
    const existingFromEncounter = await caseRepository.findBySourceEncounterId(encounterId);
    if (existingFromEncounter) return;
  }

  const age = ageFromBirthDate(patient.birthDate, encounterDate);
  const ageGroup = ageGroupFromAge(age);

  const ongoing = await findOngoingCase(patient.id, diagnosis.diseaseId);

  if (ongoing) {
    await caseRepository.update(ongoing.id, {
      status: 'CONFIRMED',
      sourceEncounterId: encounterId,
      dateReported: encounterDate,
      age,
      ageGroup,
      sex: patient.sex ?? undefined,
      facilityId: facilityId ?? undefined,
      notes: `Upgraded to CONFIRMED from EMR encounter ${encounterId}.`,
    });
  } else {
    await caseRepository.create({
      disease: { connect: { id: diagnosis.diseaseId } },
      barangay: { connect: { id: patient.barangayId } },
      reporter: { connect: { id: reportedBy } },
      patient: { connect: { id: patient.id } },
      sourceEncounterId: encounterId,
      facilityId: facilityId ?? undefined,
      autoGenerated: true,
      dateReported: encounterDate,
      age,
      ageGroup,
      sex: patient.sex ?? undefined,
      status: 'CONFIRMED',
      outcome: 'ONGOING',
      source: 'RHU',
      notes: `Auto-generated from EMR encounter ${encounterId}.`,
    });
  }

  scheduleEarlyWarning(patient.barangayId, diagnosis.diseaseId);
}

/** Process all diagnoses from an encounter and upsert confirmed cases. */
export async function generateCasesFromEncounterDiagnoses(params: {
  diagnoses: DiagnosisInput[];
  patient: PatientContext;
  barangayId: string | null;
  facilityId: string | null;
  encounterId: string;
  encounterDate: Date;
  reportedBy: string;
  skipIfEncounterCaseExists?: boolean;
}): Promise<void> {
  const patient = { ...params.patient, barangayId: params.barangayId ?? params.patient.barangayId };
  if (!patient.barangayId) return;

  for (const dx of params.diagnoses) {
    await upsertConfirmedFromEncounter({
      patient,
      diagnosis: dx,
      encounterId: params.encounterId,
      encounterDate: params.encounterDate,
      facilityId: params.facilityId,
      reportedBy: params.reportedBy,
      skipIfEncounterCaseExists: params.skipIfEncounterCaseExists,
    });
  }
}
